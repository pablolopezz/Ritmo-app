import { readdir,readFile,writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../dist/',import.meta.url));
async function walk(dir='') {
  const found=[];
  for(const entry of await readdir(root+dir,{withFileTypes:true})) {
    const path=dir+entry.name;
    if(entry.isDirectory())found.push(...await walk(path+'/'));
    else if(path!=='sw.js'&&!path.startsWith('downloads/'))found.push(path);
  }
  return found;
}
const files=(await walk()).sort(),hash=createHash('sha256');
for(const file of files) hash.update(await readFile(root+file));
const version='dieta-gym-'+hash.digest('hex').slice(0,14);
const urls=['./',...files.map(f=>'./'+f)];
const worker=`// Generated by scripts/build-sw.mjs. Update atomically, keeping old clients intact.
const CACHE=${JSON.stringify(version)};
const ASSETS=${JSON.stringify(urls)};
self.addEventListener('install',event=>event.waitUntil((async()=>{
  const cache=await caches.open(CACHE);
  try {
    for(const path of ASSETS) {
      const response=await fetch(new Request(path,{cache:'reload',credentials:'same-origin'}));
      if(!response.ok||response.redirected)throw new Error('Asset unavailable: '+path);
      const type=response.headers.get('content-type')||'';
      if((path.endsWith('.js')&&!/javascript/.test(type))||(path.endsWith('.json')&&!/json/.test(type)))throw new Error('Unexpected response type: '+path);
      await cache.put(path,response);
    }
  } catch(error) {await caches.delete(CACHE);throw error;}
})()));
self.addEventListener('message',event=>{if(event.data?.type==='SKIP_WAITING')self.skipWaiting();});
self.addEventListener('activate',event=>event.waitUntil((async()=>{
  // Retain previous versions for open clients; delete them on a later activation.
  const keys=(await caches.keys()).filter(k=>k.startsWith('dieta-gym-'));
  for(const key of keys.slice(0,-2))if(key!==CACHE)await caches.delete(key);
  await self.clients.claim();
})()));
self.addEventListener('fetch',event=>{
  const url=new URL(event.request.url);
  if(event.request.method!=='GET'||url.origin!==self.location.origin)return;
  const local=url.pathname.slice(new URL('./',self.location).pathname.length);
  // Authentication/provider routes stay on the network and are never cached.
  if(local.startsWith('signin')||local.startsWith('signout')||local.startsWith('oauth'))return;
  const asset=ASSETS.includes('./'+local)||event.request.mode==='navigate';
  if(!asset)return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    const path=event.request.mode==='navigate'&&!ASSETS.includes('./'+local)?'./index.html':url.pathname;
    const cached=await cache.match(path,{ignoreSearch:true});
    if(cached)return cached;
    return fetch(event.request);
  })());
});
`;
await writeFile(root+'sw.js',worker);
console.log('Service worker:',version,'—',files.length,'assets');
